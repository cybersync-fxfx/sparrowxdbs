function deriveVaultMasterKey(): Buffer {
  const raw = (process.env.AI_VAULT_MASTER_KEY || `${sessionSecret()}:sparrowx-ai-env-vault:v1`).trim();
  return crypto.createHash("sha256").update(raw, "utf8").digest();
}

/**
 * Encrypts a single tenant environment secret using AES-256-GCM with a 96-bit random IV.
 * Stored as ciphertext + iv + authTag; decrypted strictly in memory during container injection.
 */
export function encryptEnvSecret(plaintext: string): EncryptedSecretBlob {
  const key = deriveVaultMasterKey();
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv("aes-256-gcm", key, iv);
  const encrypted = Buffer.concat([cipher.update(plaintext, "utf8"), cipher.final()]);
  const authTag = cipher.getAuthTag();
  return {
    ciphertextHex: encrypted.toString("hex"),
    ivHex: iv.toString("hex"),
    authTagHex: authTag.toString("hex"),
    keyVersion: 1,
    updatedAt: new Date().toISOString(),
  };
}

/**
 * Decrypts an AES-256-GCM encrypted secret blob in memory.
 */
export function decryptEnvSecret(blob: EncryptedSecretBlob): string {
  const key = deriveVaultMasterKey();
  const decipher = crypto.createDecipheriv(
    "aes-256-gcm",
    key,
    Buffer.from(blob.ivHex, "hex"),
  );
  decipher.setAuthTag(Buffer.from(blob.authTagHex, "hex"));
  const decrypted = Buffer.concat([
    decipher.update(Buffer.from(blob.ciphertextHex, "hex")),
    decipher.final(),
  ]);
  return decrypted.toString("utf8");
}

export function maskSecretValue(plain: string): string {
  if (!plain) return "••••••••";
  if (plain.length <= 6) return "••••••••";
  return `${plain.slice(0, 4)}••••••••${plain.slice(-3)}`;
}

/**
 * Generates hardened Nginx reverse-proxy route config for `*.ai.sparrowx.net` and custom domains.
 * Enforces HTTP/2, Let's Encrypt TLS, mandatory WebSocket Upgrade headers, and optional sec.sparrowx.net WAF headers.
 */
export function generateNginxInstanceConfig(params: {
  hostname: string;
  internalIp: string;
  internalPort: number;
  portMbps: number;
  webhookWafEnabled: boolean;
}): string {
  const safeHost = params.hostname.replace(/[^a-z0-9.-]/gi, "");
  const rateKbps = Math.max(1024, Math.floor((params.portMbps * 1000) / 8));
  return `# Auto-generated by SparrowX AI Edge Router (OVH BOM1)
server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${safeHost};

    ssl_certificate     /etc/letsencrypt/live/${safeHost.endsWith(".ai.sparrowx.net") ? "ai.sparrowx.net" : safeHost}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${safeHost.endsWith(".ai.sparrowx.net") ? "ai.sparrowx.net" : safeHost}/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;

    # Per-tenant bandwidth ceiling (${params.portMbps} Mbps shared port)
    limit_rate ${rateKbps}k;
    client_max_body_size 50m;
${
  params.webhookWafEnabled
    ? `
    # sec.sparrowx.net Edge WAF + Webhook Replay Guard
    add_header X-SparrowX-WAF "active-l7-mumbai" always;
    limit_req zone=sparrowx_ai_webhook burst=40 nodelay;`
    : ""
}

    location / {
        proxy_pass http://${params.internalIp}:${params.internalPort};
        proxy_http_version 1.1;

        # Mandatory WebSocket & SSE streaming headers (Langflow, MCP SSE, xterm.js)
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;

        proxy_buffering off;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
    }
}`;
}

/**
 * Generates equivalent Caddy v2 route block with automatic Let's Encrypt SSL & WebSocket pass-through.
 */
export function generateCaddyInstanceConfig(params: {
  hostname: string;
  internalIp: string;
  internalPort: number;
  webhookWafEnabled: boolean;
}): string {
  const safeHost = params.hostname.replace(/[^a-z0-9.-]/gi, "");
  return `${safeHost} {
    encode zstd gzip
    header {
        Strict-Transport-Security "max-age=31536000; includeSubDomains"
        X-SparrowX-Region "IN-BOM1"
        ${params.webhookWafEnabled ? 'X-SparrowX-WAF "sec.sparrowx.net/active"' : 'X-SparrowX-WAF "bypass"'}
    }
    reverse_proxy ${params.internalIp}:${params.internalPort} {
        flush_interval -1
        header_up Host {upstream_hostport}
        header_up X-Real-IP {remote_host}
    }
}`;
}

/**
 * Builds the exact Docker isolation & Linux tc / Proxmox net0 enforcement command spec.
 */
export function buildProvisioningEnforcementSpec(params: {
  containerName: string;
  image: string;
  vcpu: number;
  ramGb: number;
  pidsLimit: number;
  portMbps: number;
  vmid: number;
}) {
  const rateMBps = Math.max(1, Math.round(params.portMbps / 8));
  return {
    dockerArgs: [
      "docker run -d",
      `--name ${params.containerName}`,
      "--restart unless-stopped",
      `--cpus="${params.vcpu}"`,
      `--memory="${params.ramGb}g"`,
      `--memory-swap="${params.ramGb}g"`,
      `--pids-limit=${params.pidsLimit}`,
      "--security-opt=no-new-privileges:true",
      "--cap-drop=ALL",
      "--cap-add=NET_BIND_SERVICE",
      "-e EXECUTIONS_DATA_PRUNE=true",
      "-e EXECUTIONS_DATA_MAX_AGE=168",
      "--log-opt max-size=25m",
      "--log-opt max-file=3",
      params.image,
    ].join(" "),
    proxmoxNetRateCmd: `qm set ${params.vmid} --net0 virtio,bridge=vmbr0,rate=${rateMBps}`,
    tcShapeCmd: `tc qdisc replace dev tap${params.vmid}i0 root tbf rate ${params.portMbps}mbit burst 256kbit latency 50ms`,
    smtpBlockRule: `nft add rule inet sparrowx_egress forward ip saddr 10.77.0.0/16 tcp dport 25 counter drop`,
  };
}

function generateMetricHistory(ramGb: number, baseCpu = 18): InstanceMetricPoint[] {
  const now = Date.now();
  const ramMaxMb = ramGb * 1024;
  return Array.from({ length: 12 }, (_, idx) => {
    const t = new Date(now - (11 - idx) * 5 * 60_000);
    const label = t.toISOString().slice(11, 16);
    const wave = Math.sin(idx * 0.7) * 6 + (idx % 3) * 2.5;
    const cpuPct = Math.max(4, Math.min(92, Number((baseCpu + wave).toFixed(1))));
    const ramMb = Math.round(ramMaxMb * (0.28 + (idx % 4) * 0.04));
    const diskIoMb = Number((1.2 + (idx % 5) * 0.9).toFixed(1));
    const netRxMbps = Number((4.5 + (idx % 6) * 2.4).toFixed(1));
    const netTxMbps = Number((7.2 + (idx % 5) * 3.1).toFixed(1));
    return { ts: label, cpuPct, ramMb, diskIoMb, netRxMbps, netTxMbps };
  });
}

