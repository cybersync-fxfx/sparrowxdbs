/**
 * Idempotent billing webhook processor for Razorpay / Cashfree events:
 * - `payment.captured` / `subscription.charged`: activates workspace instances & clears grace period
 * - `subscription.halted`: sets 3-day grace period, then pauses instances if unresolved
 */
export function processAiBillingWebhookEvent(params: {
  eventId: string;
  eventType: "payment.captured" | "subscription.charged" | "subscription.halted";
  workspaceId: string;
  amountInr?: number;
}): { applied: boolean; affectedInstances: number; action: string } {
  ensureSeededControlPlane();
  if (processedBillingEvents.has(params.eventId)) {
    return { applied: false, affectedInstances: 0, action: "duplicate_ignored" };
  }
  processedBillingEvents.add(params.eventId);

  const targets = Array.from(instanceStore.values()).filter(
    (item) => item.record.workspaceId === params.workspaceId,
  );

  if (params.eventType === "payment.captured" || params.eventType === "subscription.charged") {
    suspendedWorkspaces.delete(params.workspaceId);
    for (const item of targets) {
      if (item.record.status === "paused") {
        item.record.status = "live";
        item.record.updatedAt = new Date().toISOString();
      }
    }
    appendAudit(
      "billing-webhook@sparrowx.net",
      `billing.${params.eventType}`,
      `${params.workspaceId} (₹${params.amountInr ?? 0})`,
      "103.174.10.24",
      "ok",
    );
    return { applied: true, affectedInstances: targets.length, action: "activated" };
  }

  // subscription.halted -> mark 3-day grace period & pause
  suspendedWorkspaces.add(params.workspaceId);
  for (const item of targets) {
    item.record.status = "paused";
    item.record.updatedAt = new Date().toISOString();
  }
  appendAudit(
    "billing-webhook@sparrowx.net",
    "billing.subscription_halted_grace_pause",
    params.workspaceId,
    "103.174.10.24",
    "warning",
  );
  return { applied: true, affectedInstances: targets.length, action: "paused_after_grace" };
}
