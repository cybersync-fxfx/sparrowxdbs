import fs from "node:fs";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

export interface ProxyRouteConfig {
  projectId: string;
  slug: string;
  domains: string[];
  upstreamHost: string;
  upstreamPort: number;
}

/**
 * Atomically configures zero-downtime reverse proxy routing for a deployed container.
 * - Preferred: Caddy Admin API (dynamic JSON routes + automatic On-Demand Let's Encrypt TLS)
 * - Fallback: Atomic Nginx server config + `nginx -t && nginx -s reload`
 */
export async function upsertProjectProxyRoute(config: ProxyRouteConfig): Promise<{
  provider: "caddy" | "nginx" | "none";
  detail: string;
}> {
  const caddyAdminUrl = process.env.CADDY_ADMIN_URL?.trim();
  const safeDomains = Array.from(
    new Set(config.domains.map((d) => d.trim().toLowerCase()).filter(Boolean)),
  );
  if (safeDomains.length === 0) {
    return { provider: "none", detail: "No hostnames configured for route." };
  }

  if (caddyAdminUrl) {
    const routeId = `spx_deploy_${config.projectId.replace(/[^a-zA-Z0-9_]/g, "_")}`;
    const routePayload = {
      "@id": routeId,
      match: [{ host: safeDomains }],
      handle: [
        {
          handler: "reverse_proxy",
          upstreams: [{ dial: `${config.upstreamHost}:${config.upstreamPort}` }],
          headers: {
            request: {
              set: {
                "X-Real-IP": ["{http.request.remote.host}"],
                "X-Forwarded-Proto": ["{http.request.scheme}"],
              },
            },
          },
        },
      ],
      terminal: true,
    };

    // Delete any existing route with the same @id, then insert atomically
    await fetch(`${caddyAdminUrl.replace(/\/+$/, "")}/id/${encodeURIComponent(routeId)}`, {
      method: "DELETE",
      signal: AbortSignal.timeout(4000),
    }).catch(() => {});

    const res = await fetch(
      `${caddyAdminUrl.replace(/\/+$/, "")}/config/apps/http/servers/spx_apps/routes`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(routePayload),
        signal: AbortSignal.timeout(5000),
      },
    );

    if (!res.ok) {
      const txt = await res.text().catch(() => "");
      throw new Error(`Caddy Admin API returned HTTP ${res.status}: ${txt.slice(0, 180)}`);
    }
    return {
      provider: "caddy",
      detail: `Caddy route ${routeId} updated for ${safeDomains.join(", ")} -> ${config.upstreamHost}:${config.upstreamPort}`,
    };
  }

  const nginxDir = process.env.SPARROWX_NGINX_APPS_DIR?.trim();
  if (nginxDir) {
    fs.mkdirSync(nginxDir, { recursive: true });
    const safeSlug = config.slug.replace(/[^a-z0-9-]/g, "");
    const targetPath = path.join(nginxDir, `app-${safeSlug}.conf`);
    const tmpPath = `${targetPath}.tmp`;
    const serverNames = safeDomains.join(" ");
    const conf = `# Auto-generated by SparrowX Deploy Worker (${config.projectId})
server {
    listen 80;
    listen 443 ssl;
    server_name ${serverNames};
    ssl_certificate /etc/nginx/ssl/fullchain.pem;
    ssl_certificate_key /etc/nginx/ssl/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size 100M;
    resolver 127.0.0.11 valid=5s ipv6=off;

    location / {
        set $upstream_target http://${config.upstreamHost}:${config.upstreamPort};
        proxy_pass $upstream_target;
        proxy_http_version 1.1;
        proxy_buffering off;
        proxy_read_timeout 3600s;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }
}
`;
    fs.writeFileSync(tmpPath, conf, "utf8");
    fs.renameSync(tmpPath, targetPath);

    try {
      await execFileAsync("docker", ["exec", "sparrowx-nginx", "nginx", "-t"], { timeout: 8000 });
      await execFileAsync("docker", ["exec", "sparrowx-nginx", "nginx", "-s", "reload"], {
        timeout: 8000,
      });
    } catch {
      await execFileAsync("nginx", ["-t"], { timeout: 8000 }).catch(() => {});
      await execFileAsync("nginx", ["-s", "reload"], { timeout: 8000 }).catch(() => {});
    }
    return {
      provider: "nginx",
      detail: `Nginx config ${targetPath} validated and reloaded for ${serverNames}`,
    };
  }

  return {
    provider: "none",
    detail: "No external proxy API configured (serving via internal Deploy gateway).",
  };
}

export async function removeProjectProxyRoute(projectId: string, slug: string): Promise<void> {
  const caddyAdminUrl = process.env.CADDY_ADMIN_URL?.trim();
  if (caddyAdminUrl) {
    const routeId = `spx_deploy_${projectId.replace(/[^a-zA-Z0-9_]/g, "_")}`;
    await fetch(`${caddyAdminUrl.replace(/\/+$/, "")}/id/${encodeURIComponent(routeId)}`, {
      method: "DELETE",
      signal: AbortSignal.timeout(4000),
    }).catch(() => {});
    return;
  }

  const nginxDir = process.env.SPARROWX_NGINX_APPS_DIR?.trim();
  if (nginxDir) {
    const safeSlug = slug.replace(/[^a-z0-9-]/g, "");
    const targetPath = path.join(nginxDir, `app-${safeSlug}.conf`);
    if (fs.existsSync(targetPath)) {
      fs.unlinkSync(targetPath);
      await execFileAsync("docker", ["exec", "sparrowx-nginx", "nginx", "-s", "reload"], {
        timeout: 8000,
      }).catch(() => {});
    }
  }
}
